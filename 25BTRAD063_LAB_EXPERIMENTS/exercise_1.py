# Installing Python
# Python is a popular programming language used for software development,
# data science, AI, and automation.
#
# Steps to install Python:
# 1. Go to the official Python website: Python Downloads
# 2. Download the latest Python version for your operating system.
# 3. Run the installer.
# 4. Important: Select "Add Python to PATH" before clicking Install Now.
# 5. Click Install Now.
# 6. Open Command Prompt and type:
#        python --version
# 7. If the version number appears, Python has been installed successfully.
